//! Segmentation tests, ported from the reference C++ suite.

use normalize_uk::rozpodil::{split_sentences, tokenize, Substring};

/// Locates each expected chunk in `text` in order, so the test cases stay
/// readable while still asserting exact byte offsets.
#[track_caller]
fn check(name: &str, actual: &[Substring<'_>], text: &str, chunks: &[&str]) {
    let mut expected = Vec::new();
    let mut offset = 0;
    for chunk in chunks {
        let pos = offset
            + text[offset..]
                .find(chunk)
                .unwrap_or_else(|| panic!("{name}: missing expected chunk {chunk:?}"));
        expected.push(Substring { start: pos, stop: pos + chunk.len(), text: chunk });
        offset = pos + chunk.len();
    }
    assert_eq!(actual, expected, "{name}");
}

#[track_caller]
fn sents(name: &str, text: &str, chunks: &[&str]) {
    check(name, &split_sentences(text), text, chunks);
}

#[track_caller]
fn toks(name: &str, text: &str, chunks: &[&str]) {
    check(name, &tokenize(text), text, chunks);
}

#[test]
fn spans_borrow_the_source() {
    let text = "Привіт! Це тест.";
    for span in split_sentences(text) {
        assert_eq!(&text[span.start..span.stop], span.text);
    }
}

#[test]
fn tokenizes_apostrophes_and_letters() {
    toks("apostrophe words", "П'ять зв’язків і мʼясо.", &["П'ять", "зв’язків", "і", "мʼясо", "."]);
    toks("ocr apostrophe words", "ІМ`Я зобов`язати.", &["ІМ`Я", "зобов`язати", "."]);
    toks(
        "ukrainian letters",
        "Ґанок, їжа, Європа й Іван.",
        &["Ґанок", ",", "їжа", ",", "Європа", "й", "Іван", "."],
    );
}

#[test]
fn tokenizes_mixed_content() {
    toks(
        "mixed tokens",
        "Науково-технічний звіт: 12,5 грн (50/64 см).",
        &["Науково-технічний", "звіт", ":", "12,5", "грн", "(", "50/64", "см", ")", "."],
    );
    toks(
        "web social tokens",
        "Пишіть на test.user@example.com або @rada, тег #Київ: https://example.com/news?id=1.",
        &[
            "Пишіть",
            "на",
            "test.user@example.com",
            "або",
            "@rada",
            ",",
            "тег",
            "#Київ",
            ":",
            "https://example.com/news?id=1",
            ".",
        ],
    );
    toks("legal number marker tokens", "№-81 і №123/2026-р.", &["№-81", "і", "№123/2026-р", "."]);
    toks(
        "compact numeric suffix tokens",
        "1991р. 78к. 50крб.",
        &["1991р", ".", "78к", ".", "50крб", "."],
    );
}

