/// Picks the one/few/many form Ukrainian grammar requires for `n`.
pub(crate) fn plural(n: u64, forms: &Forms) -> &'static str {
    plural_of(n, forms.one, forms.few, forms.many)
}

/// [`plural`] over forms that are not `'static`.
pub(crate) fn plural_of<'a>(n: u64, one: &'a str, few: &'a str, many: &'a str) -> &'a str {
    if n % 10 == 1 && n % 100 != 11 {
        one
    } else if (2..=4).contains(&(n % 10)) && !(12..=14).contains(&(n % 100)) {
        few
    } else {
        many
    }
}

/// Rewrites a trailing `один`/`два` into their feminine forms.
pub(crate) fn feminine_last(words: &mut [String]) {
    if let Some(last) = words.last_mut() {
        match last.as_str() {
            "один" => *last = "одна".into(),
            "два" => *last = "дві".into(),
            _ => {}
        }
    }
}

/// Rewrites a trailing `один` into its neuter form.
pub(crate) fn neuter_last(words: &mut [String]) {
    if let Some(last) = words.last_mut() {
        if last == "один" {
            *last = "одне".into();
        }
    }
}

fn map(pairs: &[(&'static str, &'static str)]) -> HashMap<&'static str, &'static str> {
    pairs.iter().copied().collect()
}

