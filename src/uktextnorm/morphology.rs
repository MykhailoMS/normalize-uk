/// Soft-stem adjective endings, used by ordinals such as `третій`.
#[rustfmt::skip]
static SOFT_ENDINGS: LazyLock<HashMap<&'static str, &'static str>> = LazyLock::new(|| {
    map(&[
        ("nom_n", "є"), ("nom_f", "я"), ("gen", "ього"), ("dat", "ьому"), ("prep", "ьому"),
        ("loc", "ьому"), ("pl", "іх"), ("loc_pl", "іх"), ("acc_f", "ю"), ("gen_f", "ьої"),
        ("ins", "ім"), ("ins_f", "ьою"), ("ins_pl", "іми"),
    ])
});

/// Inflects an ordinal stem such as `перший` into the requested form.
///
/// Unknown forms leave the stem untouched, matching the reference behaviour.
pub(crate) fn inflect_ordinal(stem: &str, form: &str) -> String {
    if form == "nom_m" {
        return stem.to_owned();
    }
    let Some(ending) = ENDINGS.get(form) else {
        return stem.to_owned();
    };
    let (base, soft) = if let Some(base) = stem.strip_suffix("ій") {
        (base, true)
    } else if let Some(base) = stem.strip_suffix("ий") {
        (base, false)
    } else {
        (stem, false)
    };
    let ending = if soft { SOFT_ENDINGS.get(form).unwrap_or(ending) } else { ending };
    format!("{base}{ending}")
}
